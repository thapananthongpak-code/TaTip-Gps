/**
 * คำนำหน้าทั่วไปที่คนพูดติดปาก แต่ไม่มีอยู่ในชื่อสถานที่จริงในแผนที่
 *
 * Nominatim จับคำแบบตรงตัว การพิมพ์คำที่ไม่มีในชื่อจริงแม้คำเดียวทำให้ไม่เจอเลย
 * ตัวอย่างที่เจอจากการทดสอบ: ชื่อจริงในแผนที่คือ "สถานีวัดพระศรีมหาธาตุ"
 * คนพิมพ์ "สถานีรถไฟฟ้าวัดพระศรีมหาธาตุ" ซึ่งเป็นคำที่ใช้เรียกกันทั่วไป แล้วได้ผลลัพธ์ศูนย์รายการ
 *
 * เรียงจากยาวไปสั้น เพื่อให้ตัด "สถานีรถไฟฟ้า" ก่อน "สถานี"
 */
const GENERIC_PREFIXES = [
  'สถานีรถไฟฟ้า',
  'สถานีรถไฟ',
  'สถานีขนส่ง',
  'ห้างสรรพสินค้า',
  'รถไฟฟ้า',
  'สถานี',
  'บีทีเอส',
  'เอ็มอาร์ที',
  'ห้าง',
  'ร้าน',
  'bts',
  'mrt',
  'arl',
]

/** เหลือน้อยกว่านี้แล้วค้นหาไม่มีความหมาย */
const MIN_REMAINDER = 2

/**
 * ตัดคำนำหน้าทั่วไปออกจากคำค้น เพื่อใช้ค้นซ้ำเมื่อครั้งแรกไม่เจออะไรเลย
 * คืน null ถ้าไม่มีอะไรให้ตัด หรือตัดแล้วเหลือสั้นเกินจนค้นหาไม่มีความหมาย
 *
 * ทดสอบแล้วช่วยได้จริง: "สถานีรถไฟฟ้าวัดพระศรีมหาธาตุ" 0 ผล -> "วัดพระศรีมหาธาตุ" 3 ผล
 */
export function relaxQuery(query: string): string | null {
  const trimmed = query.trim()
  const lower = trimmed.toLowerCase()

  for (const prefix of GENERIC_PREFIXES) {
    if (!lower.startsWith(prefix)) continue

    const remainder = trimmed.slice(prefix.length).trim()
    if (remainder.length < MIN_REMAINDER) return null
    return remainder
  }

  return null
}

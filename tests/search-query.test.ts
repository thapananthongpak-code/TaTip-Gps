import { describe, expect, it } from 'vitest'
import { queryVariants, shortenedQueries } from '@/utils/query'

/**
 * ทั้ง Nominatim และ Photon จับคำแบบตรงตัว ไม่รู้จักตัวย่อภาษาไทยเลย
 * ทดสอบจริงพบว่า "ร.พ.ศิริราช" ได้ "ถนน ร.พ.ช." และ "รร.สวนกุหลาบ" ไม่เจออะไรเลย
 */
describe('queryVariants', () => {
  it.each([
    ['รพ.ศิริราช', 'โรงพยาบาลศิริราช'],
    ['ร.พ.รามาธิบดี', 'โรงพยาบาลรามาธิบดี'],
    ['รพ ศิริราช', 'โรงพยาบาลศิริราช'],
    ['สภ.เมือง', 'สถานีตำรวจภูธรเมือง'],
    ['มธ.ท่าพระจันทร์', 'มหาวิทยาลัยธรรมศาสตร์ท่าพระจันทร์'],
    ['อบต.บางพลี', 'องค์การบริหารส่วนตำบลบางพลี'],
  ])('ขยายตัวย่อใน "%s"', (input, expected) => {
    expect(queryVariants(input)).toContain(expected)
  })

  it('ตัวย่อที่มีความหมายได้หลายแบบ ต้องลองทุกแบบ ไม่เดาแทนผู้ใช้', () => {
    const variants = queryVariants('รร.สวนกุหลาบ')
    expect(variants).toContain('โรงเรียนสวนกุหลาบ')
    expect(variants).toContain('โรงแรมสวนกุหลาบ')
  })

  it('ตัดคำนำหน้าที่ยาวที่สุดก่อน ไม่ใช่ตัดแค่คำสั้น', () => {
    // ถ้าตัด "สถานี" ก่อน จะเหลือ "รถไฟฟ้าวัดพระศรีมหาธาตุ" ซึ่งยังหาไม่เจอ
    expect(queryVariants('สถานีรถไฟฟ้าวัดพระศรีมหาธาตุ')).toContain('วัดพระศรีมหาธาตุ')
  })

  it.each([
    ['ห้างเซ็นทรัลลาดพร้าว', 'เซ็นทรัลลาดพร้าว'],
    ['BTS อโศก', 'อโศก'],
    ['mrt ลาดพร้าว', 'ลาดพร้าว'],
  ])('ตัดคำนำหน้าทั่วไปออกจาก "%s"', (input, expected) => {
    expect(queryVariants(input)).toContain(expected)
  })

  it('เติมวรรคหน้าตัวเลขที่เขียนติดกัน', () => {
    expect(queryVariants('หมอชิต2')).toContain('หมอชิต 2')
  })

  it('ไม่เสนอรูปแบบเมื่อคำค้นถูกต้องอยู่แล้ว', () => {
    expect(queryVariants('วัดพระศรีมหาธาตุ')).toEqual([])
    expect(queryVariants('เซ็นทรัลเวิลด์')).toEqual([])
  })

  it('ไม่ขยายตัวย่อถ้าเหลือส่วนที่เหลือสั้นเกินกว่าจะค้นหาได้', () => {
    // "โรงพยาบาลก" ไม่มีความหมาย จึงต้องไม่เสนอ แม้จะยังเสนอรูปแบบอื่นได้
    expect(queryVariants('รพ.ก')).not.toContain('โรงพยาบาลก')
  })
})

describe('shortenedQueries', () => {
  it('ตัดคำท้ายออกทีละคำสำหรับคำค้นที่มีวรรค', () => {
    expect(shortenedQueries('สยามพารากอน ชั้น 3')).toContain('สยามพารากอน ชั้น')
  })

  it('ตัดตัวอักษรท้ายออกสำหรับคำไทยที่เขียนติดกัน', () => {
    // คนสะกดผิดตอนท้ายคำบ่อยกว่าตอนต้น การตัดท้ายจึงมีโอกาสเจอสิ่งที่ตั้งใจหา
    const shortened = shortenedQueries('สยามพารากอนน')
    expect(shortened.some((q) => 'สยามพารากอนน'.startsWith(q) && q.length < 12)).toBe(true)
  })

  it('ไม่คืนคำที่สั้นจนค้นหาแล้วไร้ความหมาย', () => {
    expect(shortenedQueries('สยาม').every((q) => q.length >= 3)).toBe(true)
  })

  it('จำกัดจำนวนรูปแบบ เพื่อไม่ให้ยิงคำขอเพิ่มเกินจำเป็น', () => {
    expect(shortenedQueries('ก ข ค ง จ ฉ ช').length).toBeLessThanOrEqual(3)
  })
})

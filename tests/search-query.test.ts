import { describe, expect, it } from 'vitest'
import { relaxQuery } from '@/utils/query'

/**
 * Nominatim จับคำแบบตรงตัว คำที่คนพูดติดปากแต่ไม่มีในชื่อจริงทำให้หาไม่เจอเลย
 * ตัวอย่างจริงที่ผู้ใช้รายงาน: ชื่อในแผนที่คือ "สถานีวัดพระศรีมหาธาตุ"
 * พิมพ์ "สถานีรถไฟฟ้าวัดพระศรีมหาธาตุ" แล้วได้ผลลัพธ์ศูนย์รายการ
 */
describe('relaxQuery', () => {
  it('ตัดคำนำหน้าที่ยาวที่สุดก่อน ไม่ใช่ตัดแค่คำสั้น', () => {
    // ถ้าตัด "สถานี" ก่อน จะเหลือ "รถไฟฟ้าวัดพระศรีมหาธาตุ" ซึ่งยังหาไม่เจอ
    expect(relaxQuery('สถานีรถไฟฟ้าวัดพระศรีมหาธาตุ')).toBe('วัดพระศรีมหาธาตุ')
  })

  it.each([
    ['รถไฟฟ้าสยาม', 'สยาม'],
    ['ห้างเซ็นทรัลลาดพร้าว', 'เซ็นทรัลลาดพร้าว'],
    ['ห้างสรรพสินค้าเซ็นทรัล', 'เซ็นทรัล'],
    ['สถานีขนส่งหมอชิต', 'หมอชิต'],
    ['ร้านกาแฟ', 'กาแฟ'],
  ])('ตัดคำนำหน้าออกจาก "%s"', (input, expected) => {
    expect(relaxQuery(input)).toBe(expected)
  })

  it('รองรับคำนำหน้าภาษาอังกฤษโดยไม่สนตัวพิมพ์เล็กใหญ่', () => {
    expect(relaxQuery('BTS อโศก')).toBe('อโศก')
    expect(relaxQuery('mrt ลาดพร้าว')).toBe('ลาดพร้าว')
  })

  it('ไม่ตัดถ้าคำนั้นเป็นส่วนหนึ่งของชื่อจริง', () => {
    expect(relaxQuery('วัดพระศรีมหาธาตุ')).toBeNull()
    expect(relaxQuery('เซ็นทรัลเวิลด์')).toBeNull()
    expect(relaxQuery('โรงพยาบาลศิริราช')).toBeNull()
  })

  it('ไม่ตัดจนเหลือสั้นเกินกว่าจะค้นหาได้', () => {
    expect(relaxQuery('สถานี')).toBeNull()
    expect(relaxQuery('ร้าน ก')).toBeNull()
  })
})
